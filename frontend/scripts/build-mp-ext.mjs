// Bundles src/mp/cartLogic.ts (cart + product mapping, titles, listing text, store list) for the Jaslow Poster
// Chrome extension as a global `JaslowCartLogic`.
//
//   npm run build:mp-ext                 → writes mp-assistant/shared/cart-logic.js and mp-assistant/poster/cart-logic.js
//   node scripts/build-mp-ext.mjs <out>  → writes only <out> (the deploy workflow uses this for the packaged zip)
//
// VITE_* settings (photo host, photo worker…) are baked in from the environment and frontend/.env, the same values
// the web app uses. With none set they stay empty, as in the committed copies.
import { build } from 'esbuild';
import { copyFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadEnv } from 'vite';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const env = { ...loadEnv('production', root, 'VITE_'), ...Object.fromEntries(Object.entries(process.env).filter(([k]) => k.startsWith('VITE_'))) };
// Only the settings the extension needs (never the Firebase keys: those live in jaslow-auth.js).
const KEEP = ['VITE_PHOTO_BASE', 'VITE_WINDOW_STICKER_BASE', 'VITE_DEFAULT_IMAGE_BASE', 'VITE_PHOTO_WORKER_URL', 'VITE_PUBLIC_ORIGIN', 'VITE_DMS_API_BASE'];
const baked = Object.fromEntries(KEEP.map((k) => [k, env[k] || '']));

const outArg = process.argv[2];
const out = outArg ? resolve(outArg) : resolve(root, '../mp-assistant/shared/cart-logic.js');

await build({
  entryPoints: [resolve(root, 'src/mp/cartLogic.ts')],
  bundle: true,
  format: 'iife',
  globalName: 'JaslowCartLogic',
  target: 'chrome110',
  outfile: out,
  define: { 'import.meta.env': JSON.stringify(baked) },
  banner: { js: '// GENERATED by frontend/scripts/build-mp-ext.mjs from frontend/src/mp/cartLogic.ts — do not edit by hand.' },
  logLevel: 'warning',
});
if (!outArg) copyFileSync(out, resolve(root, '../mp-assistant/poster/cart-logic.js'));
console.log(`cart-logic.js written${outArg ? ` to ${out}` : ' (shared + poster)'}; settings: ${KEEP.filter((k) => baked[k]).join(', ') || 'none'}`);
